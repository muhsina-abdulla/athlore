// Generates the Supabase "update defaults" migration from the app's own default
// lists, so the ids and names in Postgres always match the ones on the phone.
//
//   node scripts/gen-supabase-seed.mjs
//
// Writes supabase/migrations/20261016000100_update_defaults.sql. Re-run it after
// changing src/db/defaults.ts. The result is idempotent, so running it more than
// once in the Supabase SQL editor is safe.
//
// It does what the app does on every launch (src/db/seed.ts):
//   1. rename a default in place when its name changed
//   2. add missing defaults
//   3. hide defaults that are no longer offered, only if no session uses them
//
// The very first seed (20261014000100_seed_defaults.sql) is history and is not
// regenerated.

import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const load = (p) => import(pathToFileURL(resolve(root, p)).href);

const {
  DEFAULT_CATEGORIES,
  DEFAULT_SESSION_TYPES,
  RETIRED_CATEGORY_IDS,
  RETIRED_SESSION_TYPE_IDS,
} = await load('src/db/defaults.ts');

const q = (text) => `'${String(text).replace(/'/g, "''")}'`;
const list = (ids) => ids.map(q).join(', ');

function section(table, label, defaults, retiredIds, usedBy) {
  const lines = [`-- ${label}`];
  for (const d of defaults) {
    lines.push(
      `update public.${table} set name = ${q(d.name)} where id = ${q(d.id)} and user_id is null and name <> ${q(d.name)};`,
    );
  }
  lines.push(
    `insert into public.${table} (id, user_id, name) values`,
    defaults.map((d) => `  (${q(d.id)}, null, ${q(d.name)})`).join(',\n'),
    'on conflict (id) do nothing;',
  );
  if (retiredIds.length > 0) {
    lines.push(
      `update public.${table} set deleted_at = now()`,
      `  where id in (${list(retiredIds)}) and user_id is null and deleted_at is null`,
      `  and not exists (${usedBy});`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

const out = [
  '-- Generated by scripts/gen-supabase-seed.mjs. Do not edit by hand.',
  '-- Brings the shared defaults (user_id is null) up to date. Idempotent.',
  '-- Run after 20261016000000_rename_session_type_tables.sql.',
  '',
  section(
    'categories',
    'Categories',
    DEFAULT_CATEGORIES,
    RETIRED_CATEGORY_IDS,
    'select 1 from public.sessions s where s.category_id = categories.id',
  ),
  section(
    'user_session_types',
    'Session types',
    DEFAULT_SESSION_TYPES,
    RETIRED_SESSION_TYPE_IDS,
    'select 1 from public.session_type_assignments a where a.session_type_id = user_session_types.id',
  ),
].join('\n');

const file = resolve(root, 'supabase/migrations/20261016000100_update_defaults.sql');
writeFileSync(file, out);
console.log(`Wrote ${file}`);
